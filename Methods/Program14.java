class Program14
{
    static double subtraction(double a, double b)
    {
        double result = a - b ;
        return result;
    }
    public static void main(String[] args)
    {
        System.out.println("result : " + subtraction(32.1,1));
        System.out.println("result : " + subtraction(32,1));
        
    }
}